"""set_rates.py — bulk-set the mutation-rate preset on existing task configs.

Usage:
    python pulse/set_rates.py --match SARS --rates sars_cov2
    python pulse/set_rates.py --match SARS --rates sars_cov2 --dry-run

Rewrites tasks/<name>.yaml in place for every task whose name contains the
--match substring, inserting (or replacing) the mutation_model section.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import yaml

from pulse.task_config import TASKS_DIR, RATE_PRESETS


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--match', required=True, help='substring matched against task names')
    ap.add_argument('--rates', required=True, help=f'preset name: {sorted(RATE_PRESETS)}')
    ap.add_argument('--mu-total', type=float, default=None)
    ap.add_argument('--dry-run', action='store_true')
    args = ap.parse_args()

    if args.rates not in RATE_PRESETS:
        ap.error(f'--rates must be one of {sorted(RATE_PRESETS)}')

    for f in sorted(os.listdir(TASKS_DIR)):
        if not f.endswith('.yaml') or args.match not in f[:-5]:
            continue
        path = os.path.join(TASKS_DIR, f)
        d = yaml.safe_load(open(path)) or {}
        mm = d.setdefault('mutation_model', {})
        old = mm.get('rates', '(default ti90_tv5)')
        mm['rates'] = args.rates
        if args.mu_total is not None:
            mm['mu_total'] = args.mu_total
        print(f'{f[:-5]}: rates {old} -> {args.rates}' + ('' if not args.dry_run else '  (dry run)'))
        if not args.dry_run:
            header = ('# Auto-generated by pulse/discover_tasks.py — edit freely, '
                      'never overwritten.\n')
            body = yaml.safe_dump(d, sort_keys=False, default_flow_style=False)
            with open(path, 'w') as fh:
                fh.write(header + body)


if __name__ == '__main__':
    main()
